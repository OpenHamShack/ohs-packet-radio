"""Colours from the OpenHamShack brand kit (brand/tokens/tokens.json,
generated by brand/tools/build_tokens.py: edit that, then copy the values
here), dark by default like the family's other instrument windows, light
on request. The system's own font: nothing is fetched or bundled.

Red is the transmit colour and nothing else uses it (the brand kit's
rule), so an operator can tell at a glance whether the station is armed or
on the air.
"""
from __future__ import annotations

DARK = {
    "bg": "#0a0e13", "surface": "#121922", "raised": "#1a232e", "line": "#2b3644",
    "ink": "#e8eef5", "ink-dim": "#a3b0bf", "ink-faint": "#6f7d8e",
    "accent": "#4fd1e8", "accent-on": "#04141a",
    "carrier": "#ffb547", "tx": "#ff6b61", "tx-fill": "#d42019", "tx-on": "#ffffff",
    "rx": "#3ddc84", "warn": "#ffc24d", "info": "#7cb8ff",
}
LIGHT = {
    "bg": "#f2f4f7", "surface": "#ffffff", "raised": "#e6eaf0", "line": "#c9d1db",
    "ink": "#0d1520", "ink-dim": "#46536a", "ink-faint": "#7d8a9c",
    "accent": "#00728f", "accent-on": "#ffffff",
    "carrier": "#955700", "tx": "#b8160f", "tx-fill": "#c81e17", "tx-on": "#ffffff",
    "rx": "#0f7038", "warn": "#8f5400", "info": "#1557b0",
}

current = dict(DARK)


def colour(name: str):
    from PyQt6.QtGui import QColor
    return QColor(current[name])


def stylesheet(c: dict) -> str:
    return f"""
    QWidget {{ background: {c['bg']}; color: {c['ink']}; }}
    QLabel, QCheckBox, QRadioButton {{ background: transparent; }}
    QCheckBox::indicator {{ width: 14px; height: 14px; border: 1px solid {c['ink-faint']}; border-radius: 3px;
                            background: {c['surface']}; }}
    QCheckBox::indicator:checked {{ background: {c['accent']}; border-color: {c['accent']}; }}
    QCheckBox::indicator:disabled {{ border-color: {c['line']}; }}
    QMainWindow, QDialog, QWizard {{ background: {c['bg']}; }}
    QFrame#card, QGroupBox {{ background: {c['surface']}; border: 1px solid {c['line']}; border-radius: 6px; }}
    QGroupBox {{ margin-top: 14px; padding: 8px; }}
    QGroupBox::title {{ subcontrol-origin: margin; left: 8px; padding: 0 4px; color: {c['ink-dim']}; }}
    QListWidget#nav {{ background: {c['surface']}; border: none; border-right: 1px solid {c['line']};
                       font-size: 14px; outline: none; }}
    QListWidget#nav::item {{ padding: 9px 14px; border-left: 3px solid transparent; }}
    QListWidget#nav::item:selected {{ background: {c['raised']}; color: {c['ink']};
                                      border-left: 3px solid {c['accent']}; }}
    QLineEdit, QComboBox, QSpinBox, QDoubleSpinBox, QPlainTextEdit, QTextEdit {{
        background: {c['surface']}; border: 1px solid {c['line']}; border-radius: 4px; padding: 4px;
        selection-background-color: {c['accent']}; selection-color: {c['accent-on']}; }}
    QPushButton {{ background: {c['raised']}; border: 1px solid {c['line']}; border-radius: 4px;
                   padding: 5px 12px; }}
    QPushButton:hover {{ border-color: {c['accent']}; }}
    QPushButton:disabled {{ color: {c['ink-faint']}; }}
    QPushButton#primary {{ background: {c['accent']}; color: {c['accent-on']}; border: none; }}
    QPushButton#arm {{ background: {c['raised']}; color: {c['tx']}; border: 1px solid {c['tx']}; font-weight: bold; }}
    QPushButton#arm:checked {{ background: {c['tx-fill']}; color: {c['tx-on']}; }}
    QTableWidget, QTableView, QTreeWidget {{ background: {c['surface']}; gridline-color: {c['line']};
                                             border: 1px solid {c['line']}; alternate-background-color: {c['raised']}; }}
    QHeaderView::section {{ background: {c['raised']}; color: {c['ink-dim']}; border: none;
                            border-right: 1px solid {c['line']}; padding: 4px; }}
    QTabWidget::pane {{ border: 1px solid {c['line']}; }}
    QTabBar::tab {{ background: {c['surface']}; padding: 6px 12px; border: 1px solid {c['line']}; }}
    QTabBar::tab:selected {{ background: {c['raised']}; border-bottom: 2px solid {c['accent']}; }}
    QLabel#dim {{ color: {c['ink-dim']}; }}
    QLabel#heading {{ font-size: 16px; font-weight: bold; }}
    QLabel#warn {{ color: {c['warn']}; }}
    QLabel#good {{ color: {c['rx']}; }}
    QLabel#bad {{ color: {c['tx']}; }}
    QFrame#linktest {{ background: {c['raised']}; border: 2px solid {c['warn']}; border-radius: 6px; }}
    QLabel#linktest {{ color: {c['warn']}; font-weight: bold; }}
    QStatusBar {{ background: {c['surface']}; border-top: 1px solid {c['line']}; }}
    QToolTip {{ background: {c['raised']}; color: {c['ink']}; border: 1px solid {c['line']}; }}
    """


def apply(app, dark: bool = True) -> None:
    current.clear()
    current.update(DARK if dark else LIGHT)
    app.setStyle("Fusion")
    app.setStyleSheet(stylesheet(current))
